//! The nftables ruleset of the server. Pocketcloud owns the whole firewall; Docker's iptables handling is off.
use crate::wireguard::{HUB_IP, VPN_CIDR, VPN_FULL_CIDR, VPN_WEB_CIDR};

/// All app networks live in this range, one /24 per app, bridge name pc-<app>.
pub const APPS_CIDR: &str = "172.30.0.0/16";
pub const BRIDGE_PREFIX: &str = "pc-";

pub struct FirewallSpec<'a> {
    /// Interface with the default route (public network)
    pub wan: &'a str,
    pub vpn_port: u16,
    /// Bridge interface name (pc-<app>) and egress policy of every running app:
    /// `all`, `none`, or a comma-separated list of allowed TCP ports
    pub bridges: &'a [(String, String)],
}

pub fn render(s: &FirewallSpec) -> String {
    let wan = s.wan;
    let port = s.vpn_port;
    let mut out = String::new();
    // only our own tables are replaced (delete and redefine in the same atomic load: a flush would keep the
    // meter sets and nftables refuses to recreate them); fail2ban keeps its f2b-table with the active bans
    out += "#!/usr/sbin/nft -f\n# Generated by pocketcloud. Edits are overwritten.\n";
    out += "table inet filter {}\ndelete table inet filter\ntable ip nat {}\ndelete table ip nat\n\n";
    out += "table inet filter {\n";
    out += "  chain input {\n";
    out += "    type filter hook input priority 0; policy drop;\n";
    out += "    iif lo accept\n";
    out += "    ct state established,related accept\n";
    out += "    ct state invalid drop\n";
    out += "    ip protocol icmp accept\n";
    out += "    ip6 nexthdr icmpv6 accept\n";
    out += &format!("    iifname \"{wan}\" tcp dport 22 accept comment \"public ssh, gated by the cloud firewall\"\n");
    out += &format!("    iifname \"{wan}\" tcp dport {{ 80, 443 }} accept comment \"caddy public\"\n");
    // the challenge nameserver: a global cap, then 20 queries per second per source; the rest is dropped
    out += &format!("    iifname \"{wan}\" meta l4proto {{ tcp, udp }} th dport 53 limit rate over 200/second drop comment \"acme nameserver global cap\"\n");
    out += &format!("    iifname \"{wan}\" meta l4proto {{ tcp, udp }} th dport 53 meter dns4 {{ ip saddr limit rate 20/second burst 40 packets }} accept comment \"acme challenge nameserver\"\n");
    out += &format!("    iifname \"{wan}\" meta l4proto {{ tcp, udp }} th dport 53 meter dns6 {{ ip6 saddr limit rate 20/second burst 40 packets }} accept comment \"acme challenge nameserver v6\"\n");
    out += &format!("    iifname \"{wan}\" udp dport {port} accept comment \"wireguard\"\n");
    out += &format!("    iifname \"wg0\" ip saddr {VPN_FULL_CIDR} accept comment \"vpn full scope\"\n");
    out += &format!("    iifname \"wg0\" ip saddr {VPN_WEB_CIDR} ip daddr {HUB_IP} tcp dport 443 accept comment \"vpn web scope: interface and internal routes\"\n");
    out += &format!("    iifname \"wg0\" ip saddr {VPN_WEB_CIDR} ip daddr {HUB_IP} meta l4proto {{ tcp, udp }} th dport 53 accept comment \"vpn web scope: dns\"\n");
    out += "  }\n";
    out += "  chain forward {\n";
    out += "    type filter hook forward priority 0; policy drop;\n";
    out += "    ct state established,related accept\n";
    out += "    ct state invalid drop\n";
    for (b, egress) in s.bridges {
        out += &format!("    iifname \"{b}\" oifname \"{b}\" accept comment \"inside one app network\"\n");
        match egress.as_str() {
            "none" => {}
            "all" => out += &format!("    iifname \"{b}\" oifname \"{wan}\" accept comment \"{b} to the internet\"\n"),
            ports => {
                let list: Vec<&str> = ports.split(',').map(str::trim).filter(|p| p.parse::<u16>().is_ok()).collect();
                if !list.is_empty() {
                    out += &format!("    iifname \"{b}\" oifname \"{wan}\" tcp dport {{ {} }} accept comment \"{b} to the internet, listed ports\"\n", list.join(", "));
                }
            }
        }
    }
    out += &format!("    iifname \"wg0\" ip saddr {VPN_FULL_CIDR} oifname \"{BRIDGE_PREFIX}*\" accept comment \"vpn full scope to apps\"\n");
    out += "  }\n";
    out += "  chain output {\n    type filter hook output priority 0; policy accept;\n  }\n";
    out += "}\n\n";
    out += "table ip nat {\n";
    out += "  chain postrouting {\n";
    out += "    type nat hook postrouting priority srcnat; policy accept;\n";
    out += &format!("    ip saddr {APPS_CIDR} oifname \"{wan}\" masquerade comment \"app egress\"\n");
    out += &format!("    ip saddr {VPN_CIDR} oifname \"{BRIDGE_PREFIX}*\" masquerade comment \"vpn clients appear as the host to apps\"\n");
    out += "  }\n";
    out += "}\n";
    out
}

/// The app network of the app with index n (1-based): 172.30.n.0/24, gateway .1, services from .10.
pub fn app_subnet(index: u32) -> String {
    format!("172.30.{index}.0/24")
}

pub fn app_gateway(index: u32) -> String {
    format!("172.30.{index}.1")
}

pub fn service_ip(index: u32, service_no: u32) -> String {
    format!("172.30.{index}.{}", 10 + service_no)
}

pub fn bridge_name(app: &str) -> String {
    // kernel interface names are limited to 15 characters
    let mut n = format!("{BRIDGE_PREFIX}{app}");
    n.truncate(15);
    n
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn renders() {
        let b = vec![("pc-web".to_string(), "all".to_string()), ("pc-api".to_string(), "587, 443".to_string()), ("pc-db".to_string(), "none".to_string())];
        let s = render(&FirewallSpec { wan: "eth0", vpn_port: 51820, bridges: &b });
        assert!(s.contains("policy drop"));
        assert!(!s.contains("flush ruleset"));
        assert!(s.contains("delete table inet filter"));
        assert!(s.contains("iifname \"pc-web\" oifname \"pc-web\" accept"));
        assert!(s.contains("iifname \"pc-web\" oifname \"eth0\" accept"));
        assert!(s.contains("iifname \"pc-api\" oifname \"eth0\" tcp dport { 587, 443 } accept"));
        assert!(!s.contains("iifname \"pc-db\" oifname \"eth0\""));
        assert!(s.contains("udp dport 51820"));
        assert!(s.contains("meter dns4 { ip saddr limit rate 20/second"));
    }

    #[test]
    fn bridge_names_fit() {
        assert_eq!(bridge_name("a-very-long-application-name").len(), 15);
    }
}
